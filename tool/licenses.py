"""Writes docs/handover/LICENSES.md: the licence of every package the app
uses, read from the local pub cache (run `flutter pub get` first).

Run from the repository root:  python3 tool/licenses.py
"""
import os
from collections import Counter

import yaml

CACHE = os.path.expanduser(os.environ.get("PUB_CACHE", "~/.pub-cache")) + "/hosted/pub.dev"


def kind(text):
    t = text[:4000].lower()
    if "apache license" in t and "version 2.0" in t:
        return "Apache-2.0"
    if "mit license" in t or "permission is hereby granted, free of charge" in t:
        return "MIT"
    if "redistribution and use in source and binary forms" in t:
        return "BSD-3-Clause" if ("neither the name" in t or "endorse or promote" in t) else "BSD-2-Clause"
    if "mozilla public license" in t:
        return "MPL-2.0"
    if "gnu lesser general public" in t:
        return "LGPL"
    if "gnu general public license" in t:
        return "GPL"
    return "to check"


def main():
    lock = yaml.safe_load(open("pubspec.lock"))
    rows = []
    for name, info in sorted(lock["packages"].items()):
        if info.get("source") != "hosted":
            continue
        version = info["version"]
        folder = f"{CACHE}/{name}-{version}"
        licence = "not in cache"
        for f in ("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING"):
            if os.path.exists(f"{folder}/{f}"):
                licence = kind(open(f"{folder}/{f}", errors="ignore").read())
                break
        rows.append((name, version, licence, info["dependency"].replace("direct main", "direct").replace("direct dev", "dev")))
    counts = Counter(r[2] for r in rows)
    with open("docs/handover/LICENSES.md", "w") as out:
        out.write("# Licences\n\nRembo is released under the **MIT licence** (`LICENSE`). This page lists what it is built from, so that a company can check it before installing it. Generated by `tool/licenses.py` from `pubspec.lock`.\n\n")
        out.write("## In short\n\n")
        out.write("| Licence | Packages |\n|---|---|\n")
        for k, n in counts.most_common():
            out.write(f"| {k} | {n} |\n")
        out.write("""
All of them allow use in an MIT project, commercial use included. Two points to know:

- **`dbus` (MPL-2.0)** is only pulled in by the Linux desktop build, which is not shipped (Android and iOS only). MPL-2.0 is file-level copyleft: it would only require publishing changes made to `dbus` itself.
- **Google ML Kit** (receipt reading on the phone): the Flutter plugin `google_mlkit_text_recognition` is MIT, but the recognition engine it downloads is Google's, free of charge and **proprietary**, under the [ML Kit terms](https://developers.google.com/ml-kit/terms). It runs offline and sends nothing to Google for recognition. An open-source engine (Tesseract, PaddleOCR) can replace it behind the same `ReceiptReader` interface; the OCR bench (`assets/bench`) measures any engine on the same 30 receipts.

## Other components

| Component | Licence | Where |
|---|---|---|
| Archivo, Instrument Sans, JetBrains Mono fonts | SIL Open Font License 1.1 | `assets/fonts/*_OFL.txt` |
| Supabase (database, auth, storage, functions) | Apache-2.0 | server side, can be self-hosted |
| Server receipt reader engine (optional) | the company's choice, e.g. Ollama (MIT) with an open-weight model | `supabase/functions/read-receipt` |
| Bench receipts (`assets/bench`) | fictional, generated by `tool/bench/generate_receipts.py` (MIT, part of Rembo) | |

## Every package

| Package | Version | Licence | Used |
|---|---|---|---|
""")
        for name, version, licence, dep in rows:
            out.write(f"| `{name}` | {version} | {licence} | {dep} |\n")
    print(dict(counts))


if __name__ == "__main__":
    main()
